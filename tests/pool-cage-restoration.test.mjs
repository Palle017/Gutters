import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
const site=new URL('../site/',import.meta.url);
test('pool cage restoration page walks through John’s process in order',async()=>{
  const doc=new JSDOM(await readFile(new URL('pool-cage-restoration.html',site),'utf8')).window.document;
  const copy=doc.querySelector('main').textContent;
  assert.equal(doc.querySelectorAll('h1').length,1);
  assert.match(doc.querySelector('h1').textContent,/Pool cage restoration/i);
  const steps=[...doc.querySelectorAll('.process-steps li')].map(li=>li.textContent.replace(/\s+/g,' ').trim());
  assert.equal(steps.length,7);
  assert.match(steps[0],/take out all the screen/i);
  assert.match(steps[1],/bushes/i);
  assert.match(steps[2],/replace all screws/i);
  assert.match(steps[3],/pressure wash/i);
  assert.match(steps[4],/drop cloths/i);
  assert.match(steps[4],/tape/i);
  assert.match(steps[5],/Tough Trim aluminum paint/i);
  assert.match(steps[6],/following day/i);
  assert.match(steps[6],/choice of screen/i);
  assert.doesNotMatch(copy,/\$\d|warrant|guarantee|discount|credit card|door kit/i);
  assert.ok(doc.querySelector('a[href="estimate.html"]'));
  assert.ok(doc.querySelector('a[href="tel:+12393553686"]'));
  assert.ok(doc.querySelector('.process-steps a[href="screen-types.html"]'));
  assert.ok(doc.querySelector('a[href="aluminum-cage-painting.html"]'));
  const painting=new JSDOM(await readFile(new URL('aluminum-cage-painting.html',site),'utf8')).window.document;
  assert.ok(painting.querySelector('main a[href="pool-cage-restoration.html"]'));
  const types=new JSDOM(await readFile(new URL('screen-types.html',site),'utf8')).window.document;
  assert.ok(types.querySelector('main a[href="pool-cage-restoration.html"]'));
});
